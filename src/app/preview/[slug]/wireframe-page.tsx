            <div className="flex items-center gap-2 text-xs text-[#BDBDBD]">
              <span>Current site score:</span>
              <span className="rounded bg-[#616161] px-2 py-0.5 font-bold text-white">{audit.overallScore}/100</span>
              <span>→ This redesign targets 85+</span>
            </div>
