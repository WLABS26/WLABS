// ---- Primitives ----

function SectionLabel({ label }: { label: string }) {
  return (
    <div className="absolute left-4 top-2 z-10">
      <span className="rounded bg-[#424242] px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide text-white">[{label}]</span>
    </div>
  );
}

function SectionBadge({ label, small }: { label: string; small?: boolean }) {
  return (
    <span className={`rounded bg-[#9E9E9E] px-2 py-0.5 font-bold uppercase tracking-wide text-white ${small ? "text-[9px]" : "text-xs"}`}>
      {label}
    </span>
  );
}

function UXAnnotation({ label, position = "inline" }: { label: string; position?: "inline" | "top-right" }) {
  const base = "rounded-full border border-dashed border-[#9E9E9E] bg-white/80 px-2 py-0.5 text-[10px] font-medium text-[#9E9E9E]";
  if (position === "top-right") {
    return <span className={`absolute right-4 top-2 z-10 ${base}`}>{label}</span>;
  }
  return <span className={base}>{label}</span>;
}

function WireframeTag({ label }: { label: string }) {
  return (
    <div className="inline-block rounded border border-[#BDBDBD] bg-white px-3 py-1 text-xs font-medium uppercase tracking-wide text-[#9E9E9E]">
      {label}
    </div>
  );
}

function WireframeCta({ label, primary, fullWidth }: { label: string; primary?: boolean; fullWidth?: boolean }) {
  return (
    <div
      className={`inline-flex items-center justify-center rounded-full px-6 py-3 text-sm font-semibold ${fullWidth ? "w-full" : ""} ${
        primary
          ? "border-2 border-[#424242] bg-[#424242] text-white"
          : "border-2 border-[#9E9E9E] bg-white text-[#616161]"
      }`}
    >
      {label}
    </div>
  );
}

function PlaceholderBox({
  width,
  height,
  label,
}: {
  width: number | string;
  height: number | string;
  label: string;
}) {
  return (
    <div
      className="flex flex-shrink-0 items-center justify-center rounded-lg border-2 border-dashed border-[#BDBDBD] bg-[#EEEEEE] text-center text-xs text-[#9E9E9E]"
      style={{ width: typeof width === "number" ? `${width}px` : width, height: typeof height === "number" ? `${height}px` : height }}
    >
      {label}
    </div>
  );
}

function WireframeCard({ children, highlighted }: { children: React.ReactNode; highlighted?: boolean }) {
  return (
    <div
      className={`rounded-2xl border-2 p-5 ${
        highlighted ? "border-[#424242] bg-white" : "border-[#BDBDBD] bg-white"
      }`}
    >
      {children}
    </div>
  );
}

function WireframeSection({
  label,
  heading,
  tinted,
  children,
}: {
  label: string;
  heading: string;
  tinted?: boolean;
  children: React.ReactNode;
}) {
  return (
    <section className={`relative border-b-2 border-dashed border-[#BDBDBD] ${tinted ? "bg-[#FAFAFA]" : "bg-white"}`}>
      <SectionLabel label={label} />
      <div className="mx-auto max-w-6xl px-4 py-14 pt-10">
        <h2 className="text-center text-2xl font-bold text-[#212121] sm:text-3xl">{heading}</h2>
        <div className="mt-8">{children}</div>
      </div>
    </section>
  );
}
